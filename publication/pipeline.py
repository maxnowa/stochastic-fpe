"""Compute side of the publication figures.

One run = one invocation of the C solver with its own parameter header,
executed in a throw-away working directory so the project's own data/ and
src/params.h are never touched. The multi-gigabyte raw output is reduced
immediately to a small .npz in publication/cache/ and then deleted.

Everything expensive lives here. The fig_*.py scripts only read the cache,
so restyling a figure never costs a simulation.
"""

