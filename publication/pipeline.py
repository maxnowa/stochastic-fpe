# Wall-clock of the most recent solver execution, excluding compilation.
# Filled by run_solver so the benchmark can time the solver without
# reimplementing the build.
LAST_RUN = {}


def run_solver(tag, params, verbose=True, patches=None):
    """Build and run the C solver for one parameter set.

    `patches` is an optional list of (old, new) string pairs applied to the
    copy of the solver source. It exists for numerical experiments on
    constants that are hard-coded in the C file, and it never touches the
    project's own source. A pattern that does not match is an error rather
    than a silent no-op.

    Returns the working directory holding data/activity.bin and
    data/density.bin. The caller is responsible for cleaning it up.
    """
    workdir = os.path.join(WORK, tag)
    shutil.rmtree(workdir, ignore_errors=True)
    os.makedirs(workdir, exist_ok=True)

    # The solver reads src/lambda_table.bin relative to its working
    # directory, so point a link at the project's src/.
    os.symlink(os.path.join(PROJECT, "src"), os.path.join(workdir, "src"))

    # Copying the source next to our own params.h makes the quoted include
    # resolve here rather than to src/params.h.
    source = os.path.join(PROJECT, "src", "stochastic_fpe.c")
    text = open(source).read()
    for old, new in (patches or []):
        if old not in text:
            raise ValueError(f"patch target not found in solver source: {old!r}")
        text = text.replace(old, new)
        if verbose:
            print(f"  patched: {old.strip()}  ->  {new.strip()}")
    with open(os.path.join(workdir, "stochastic_fpe.c"), "w") as fh:
        fh.write(text)
    write_header(os.path.join(workdir, "params.h"), params)

    binary = os.path.join(workdir, "solver")
    compile_cmd = ["gcc", "stochastic_fpe.c", "-o", "solver",
                   "-O3", "-Wall", "-lm", "-march=native", "-flto"]
    if verbose:
        print(f"  compiling {tag} ...")
    subprocess.run(compile_cmd, cwd=workdir, check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)

    if verbose:
        print(f"  running solver ({configs.describe_params(params)}) ...")
    t0 = time.time()
    proc = subprocess.run([binary], cwd=workdir, check=True,
                          stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True)
    LAST_RUN["seconds"] = time.time() - t0
    LAST_RUN["tag"] = tag
    if verbose:
        tail = proc.stdout.strip().splitlines()
        print(f"  solver finished in {time.time() - t0:.0f} s")
        for line in tail[:2]:
            print(f"    {line}")

    return workdir


# ==========================================================================
# Spectral estimation
# ==========================================================================
def periodogram_welch_free(data, dt, df=1.0):
    """Bartlett periodogram, accumulated one segment at a time.

    Numerically identical to analysis.utils.periodogram but never holds more
    than a single segment in memory, which matters because a 40 s run is
    ~10^8 samples. Uses rfft since only the positive half is returned.
    """
    nfft = int(1.0 / (dt * df) + 0.5)
    df_out = 1.0 / (nfft * dt)
    ntrials = int(len(data) / nfft)
    if ntrials < 1:
        raise ValueError(
            f"series too short: {len(data)} samples < NFFT {nfft}")

    keep = nfft // 2
    acc = np.zeros(keep - 1, dtype=np.float64)
    for k in range(ntrials):
        seg = np.asarray(data[k * nfft:(k + 1) * nfft], dtype=np.float64)
        spec = np.fft.rfft(seg)[1:keep]
        acc += (spec.real ** 2 + spec.imag ** 2)

    psd = acc * dt / (nfft - 1) / ntrials
    freq = df_out * np.arange(keep - 1) + df_out
    return freq, psd


def spectrum(activity_hz, dt_sec, bins_per_decade=20, skip_ms=0.0):
    """Spectrum of the stationary part of a trace.

    `skip_ms` discards the start before estimating. This matters more than it
    looks: the Bartlett segments are one second long, so any startup
    transient lands wholly inside the first segment and is averaged over only
    the number of segments. A rate step of a few hundred Hz lasting tens of
    milliseconds carries orders of magnitude more low-frequency power than
    the finite-size plateau being measured, and silently inflates it.
    """
    if skip_ms > 0.0:
        skip = int(skip_ms / 1000.0 / dt_sec)
        activity_hz = activity_hz[skip:]
    freq, psd = periodogram_welch_free(activity_hz, dt_sec, df=1.0)
    return log_smooth(freq, psd, bins_per_decade=bins_per_decade)


# ==========================================================================
# Microscopic reference network
# ==========================================================================
# Euler-Maruyama only tests the threshold at sample points, so a path that
# crosses and returns inside one step is never counted. The reference network
# therefore fires too slowly, and the whole activity spectrum sits low by the
# same factor, since its high-frequency plateau is just the rate over N. The
# deficit scales as sqrt(dt) and is worst where firing is noise-driven: 7.5%
# subthreshold at low noise against 1.3% suprathreshold.
#
# The remedy is detection, not refinement. Given both endpoints below the
# threshold b and increment variance s2, a Brownian bridge crossed with
# probability exp(-2 (b - v0)(b - v1) / s2). Drawing against that restores
# first-order convergence of the hitting time, and costs one exponential and
# one uniform per step rather than the sixteen-fold step refinement that would
# be needed to get even half as close. Measured against the exact rate:
#
#   subthreshold  low noise    -7.45%  ->  +0.43%
#   suprathreshold low noise   -1.27%  ->  +0.10%
#
# Refining on top of the correction moves it only to +0.24% and +0.03%, so
# what is left is no longer crossing bias.
MICRO_BRIDGE = True


def run_micro(params, t_max_ms, seed=1, verbose=True, bridge=None):
    """N uncoupled/coupled LIF Langevin neurons, Euler-Maruyama.

    Port of validation.check_psd.run_network, minus the per-neuron spike-time
    bookkeeping that the spectrum does not use, plus the Brownian-bridge exit
    correction described at MICRO_BRIDGE. Pass bridge=False for the
    uncorrected scheme.
    """
    rng = np.random.default_rng(seed)
    # Separate stream for the bridge draws, so switching the correction on
    # leaves the Gaussian increments bit-identical to an uncorrected run.
    aux = np.random.default_rng(seed + 90_000)
    if bridge is None:
        bridge = MICRO_BRIDGE

    n = int(params["N_NEURONS"])
    mu = params["MU"]
    d = params["D"]
    tau = params["TAU"]
    v_th = params["V_TH"]
    v_reset = params["V_RESET"]
    dt = params["DT_NET"]
    w = params["W"]
    p = params["CONNECTIVITY"]
    delay = params["DELAY"]
    recurrent = bool(params["RECURRENCE"]) and w != 0.0

    steps = int(t_max_ms / dt)
    dt_sec = dt / 1000.0
    activity = np.zeros(steps, dtype=np.float32)

    buffer_size = int(delay / dt) + 1
    spike_buffer = np.zeros((buffer_size, n), dtype=np.float32)

    # Sparse storage once the connectivity is dilute: a dense N-by-N matrix
    # is what stops the interesting regime from being reachable at all, since
    # separating random from full connectivity needs few inputs per neuron
    # while keeping the feedback noise low needs a large population.
    conn = None
    sparse_conn = None
    if recurrent and p < 1.0:
        if p <= 0.2 and n >= 1000:
            from scipy import sparse as _sp
            sparse_conn = _sp.random(
                n, n, density=p, format="csr", random_state=rng,
                data_rvs=lambda size: np.full(size, w / p, dtype=np.float32),
                dtype=np.float32)
            if verbose:
                print(f"    sparse connectivity: {sparse_conn.nnz:,} "
                      f"synapses, {sparse_conn.nnz / n:.0f} per neuron")
        else:
            conn = (rng.random((n, n)) < p).astype(np.float32) * (w / p)

    v = np.zeros(n)
    drift_factor = dt / tau
    noise_factor = np.sqrt(2.0 * d / tau) * np.sqrt(dt)
    step_var = noise_factor * noise_factor

    if verbose:
        kind = ("all-to-all" if p >= 1.0 else f"random p={p:g}") \
            if recurrent else "unconnected"
        print(f"  microscopic network: N={n}, {steps:,} steps, {kind}"
              + (", bridge-corrected" if bridge else ""))

    write_idx = 0
    report = max(1, steps // 20)
    t0 = time.time()

    for i in range(steps):
        kick = 0.0
        if recurrent:
            delayed = spike_buffer[(write_idx + 1) % buffer_size]
            if p >= 1.0:
                kick = ((w / n) / tau) * delayed.sum()
            elif sparse_conn is not None:
                kick = (sparse_conn @ delayed) / n / tau
            else:
                kick = (conn @ delayed) / n / tau

        v_old = v
        v = v_old + (mu - v_old) * drift_factor \
            + rng.standard_normal(n) * noise_factor + kick

        spikes = v >= v_th
        if bridge:
            below = ~spikes
            gap = (v_th - v_old[below]) * (v_th - v[below])
            crossed = aux.random(below.sum()) < np.exp(-2.0 * gap / step_var)
            spikes[np.flatnonzero(below)[crossed]] = True
        v = np.where(spikes, v_reset, v)
        activity[i] = spikes.sum() / (n * dt_sec)

        if recurrent:
            spike_buffer[write_idx] = spikes
        write_idx = (write_idx + 1) % buffer_size

        if verbose and i % report == 0 and i:
            frac = i / steps
            eta = (time.time() - t0) * (1.0 / frac - 1.0)
            print(f"    {frac * 100:3.0f}%  eta {eta:5.0f} s", end="\r",
                  flush=True)

    if verbose:
        print(f"    microscopic network done in {time.time() - t0:.0f} s"
              + " " * 20)
    return activity


