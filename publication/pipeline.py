# Reduction: raw binaries -> cache entry
# ==========================================================================
def downsample(x, target):
    step = max(1, len(x) // target)
    return np.asarray(x[::step], dtype=np.float64), step


def moving_average(x, window):
    """Centred moving average with the invalid edges set to NaN.

    'same'-mode convolution tapers towards zero at both ends, which shows up
    as a fake dive at t=0 and t=T. NaN-ing those samples makes matplotlib
    skip them instead of drawing the artefact.
    """
    if window < 2:
        return np.asarray(x, dtype=np.float64)
    kernel = np.ones(window) / window
    out = np.convolve(x, kernel, mode="same").astype(np.float64)
    out[:window] = np.nan
    out[-window:] = np.nan
    return out


def reduce_run(tag, params, workdir, want_micro, want_exact,
               trace_points=40000, n_snapshots=6, verbose=True):
    """Turn the raw solver output into the compact arrays a figure needs."""
    grid_n = int(params["GRID_N"])
    t_max = params["T_MAX"]

    act = np.memmap(os.path.join(workdir, "data", "activity.bin"),
                    dtype=np.float32, mode="r").reshape(-1, 2)
    dens = np.memmap(os.path.join(workdir, "data", "density.bin"),
                     dtype=np.float32, mode="r").reshape(-1, grid_n)

    n_steps = act.shape[0]
    dt_ms = t_max / n_steps
    dt_sec = dt_ms / 1000.0

    out = {
        "tag": tag,
        "label": configs.describe_params(params),
        "t_max_ms": t_max,
        "n_steps": n_steps,
        "dt_ms": dt_ms,
        "grid_n": grid_n,
    }
    for key, val in params.items():
        out[f"param_{key}"] = val

    # --- voltage grid -----------------------------------------------------
    dx = (configs.V_MAX - configs.V_MIN) / grid_n
    out["v_grid"] = configs.V_MIN + dx * np.arange(grid_n)
    out["dx"] = dx

    # --- density ----------------------------------------------------------
    n_snap = dens.shape[0]
    idx = np.linspace(0, n_snap - 1, n_snapshots, dtype=int)
    out["density_snapshots"] = np.asarray(dens[idx], dtype=np.float64)
    out["density_times_ms"] = idx * (t_max / n_snap)
    # Stationary density: average over the second half of the run.
    half = n_snap // 2
    out["density_stationary"] = np.asarray(
        dens[half:], dtype=np.float64).mean(axis=0)

    # --- rate and mass traces --------------------------------------------
    rate_ds, step = downsample(act[:, 0], trace_points)
    rate_ds *= 1000.0                      # kHz -> Hz
    mass_ds, _ = downsample(act[:, 1], trace_points)
    t_ds = np.linspace(0.0, t_max, len(rate_ds))

    out["t_ms"] = t_ds
    out["rate_hz"] = rate_ds
    out["mass"] = mass_ds
    out["downsample_step"] = step

    dt_ds_ms = t_max / len(rate_ds)
    out["rate_hz_smooth10"] = moving_average(
        rate_ds, max(1, int(10.0 / dt_ds_ms)))
    out["mass_smooth100"] = moving_average(
        mass_ds, max(1, int(100.0 / dt_ds_ms)))
    out["smooth_window_bins"] = max(1, int(10.0 / dt_ds_ms))
    out["mass_window_bins"] = max(1, int(100.0 / dt_ds_ms))

    # A short window at full time resolution, taken from the stationary part
    # of the run. The downsampled trace above is fine for showing 40 s of
    # stationarity but averages away the structure of A(t); panels that need
    # to show what the activity actually looks like use this instead.
    excerpt_ms = 100.0
    start = int(0.6 * n_steps)
    count = int(min(excerpt_ms / dt_ms, n_steps - start))
    out["excerpt_t_ms"] = dt_ms * np.arange(count)
    out["excerpt_rate_hz"] = np.asarray(
        act[start:start + count, 0], dtype=np.float64) * 1000.0
    out["excerpt_mass"] = np.asarray(
        act[start:start + count, 1], dtype=np.float64)
    out["excerpt_dt_ms"] = dt_ms
    out["excerpt_start_ms"] = start * dt_ms

    # Statistics over the full-resolution series, skipping a 30% transient.
    stride = max(1, n_steps // 2_000_000)
    tail = np.asarray(act[int(0.3 * n_steps)::stride, :], dtype=np.float64)
    out["rate_mean_hz"] = float(tail[:, 0].mean() * 1000.0)
    out["mass_mean"] = float(tail[:, 1].mean())
    out["mass_final"] = float(act[-1, 1])

    # Reference stationary rate (Siegert).
    mu_dim = (params["MU"] - params["V_RESET"]) / \
        (params["V_TH"] - params["V_RESET"])
    sigma_dim = np.sqrt(params["D"]) / (params["V_TH"] - params["V_RESET"])
    rate_siegert = rate_whitenoise_benji(mu_dim, sigma_dim) * \
        (1000.0 / params["TAU"])
    out["rate_siegert_hz"] = float(rate_siegert)
    cv, _ = derived(params)
    out["cv"] = float(cv)

    # --- spectra ----------------------------------------------------------
    # Only worth computing when the run is long enough and did not collapse.
    if t_max >= 20000.0:
        if verbose:
            print("  spectrum of solver output ...")
        activity_hz = np.asarray(act[:, 0], dtype=np.float64) * 1000.0
        f_meso, p_meso = spectrum(activity_hz, dt_sec)
        del activity_hz
        out["freq_meso"] = f_meso
        out["psd_meso"] = p_meso

        if want_micro:
            micro = run_micro(params, t_max, verbose=verbose)
            f_mic, p_mic = spectrum(micro.astype(np.float64),
                                    params["DT_NET"] / 1000.0)
            out["freq_micro"] = f_mic
            out["psd_micro"] = p_mic
            out["micro_rate_mean_hz"] = float(micro.mean())
            del micro

        if want_exact:
            if verbose:
                print("  analytical spectrum ...")
            # The theory is a ratio of parabolic cylinder functions and
            # stays numerically flat and stable out to 400 kHz, and costs a
            # third of a second for a whole grid, so there is no reason to
            # truncate it. The old 2500 Hz cap left the analytical curve
            # dangling part-way across the panel.
            mask = f_meso > 0.5
            f_th = f_meso[mask]
            out["freq_exact"] = f_th
            out["psd_exact"] = exact_spectrum(f_th, params, rate_siegert)
            out["psd_poisson_level"] = rate_siegert / params["N_NEURONS"]
            out["psd_lowfreq_level"] = \
                rate_siegert * cv ** 2 / params["N_NEURONS"]

    return out


def deviation_metrics(f_ref, p_ref, f_test, p_test, f_min=1.0, f_max=10000.0):
    """Log-spectral distance and relative RMSE of `test` against `ref`."""
    mask = (f_test >= f_min) & (f_test <= f_max)
    f_eval = f_test[mask]
    p_eval = p_test[mask]
    p_interp = np.interp(f_eval, f_ref, p_ref)
    lsd = float(np.sqrt(np.mean((np.log10(p_interp)
                                 - np.log10(p_eval)) ** 2)))
    rmse = float(np.sqrt(np.mean((p_interp - p_eval) ** 2)))
    return lsd, rmse / float(np.mean(p_eval))


# ==========================================================================
# Cache front end
# ==========================================================================
def cache_path(tag):
    return os.path.join(CACHE, f"{tag}.npz")


def ensure(tag, force=False, keep_raw=False, verbose=True):
    """Return the cached arrays for `tag`, computing them if needed."""
    path = cache_path(tag)
    if os.path.exists(path) and not force:
        if verbose:
            print(f"[cache] {tag}")
        return np.load(path, allow_pickle=True)

    params = configs.RUNS[tag]
    print(f"[compute] {tag}: {configs.describe(tag)}")
    os.makedirs(CACHE, exist_ok=True)

    workdir = run_solver(tag, params, verbose=verbose)
    try:
        data = reduce_run(tag, params, workdir,
                          want_micro=configs.needs_micro(tag),
                          want_exact=configs.needs_exact(tag),
                          verbose=verbose)
        np.savez_compressed(path, **data)
        size_mb = os.path.getsize(path) / 1e6
        print(f"  cached -> {path} ({size_mb:.1f} MB)")
    finally:
        if not keep_raw:
            shutil.rmtree(workdir, ignore_errors=True)

    return np.load(path, allow_pickle=True)


def load(tag):
    path = cache_path(tag)
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"no cache for '{tag}'. Run: python publication/make.py compute "
            f"--only {tag}")
    return np.load(path, allow_pickle=True)


def val(data, key, default=None):
    """Read a scalar out of a loaded .npz (they come back as 0-d arrays)."""
    if key not in data:
        return default
    arr = data[key]
    return arr.item() if arr.ndim == 0 else arr


# ==========================================================================
# Ensemble runs: several independent realisations of the same condition
# ==========================================================================
# Run-to-run scatter in the low-frequency plateau is about 3%, which is the
# same size as several of the effects worth reporting. A single realisation
# therefore cannot support a claim at that level, so the spectra in the
# figures are means over independent seeds with a band showing the spread.

def seed_patch(seed):
    """Inject an RNG seed. The solver never calls srand(), so without this
    every run replays the identical noise realisation."""
    return [("// seed_rng((uint64_t)time(NULL));", f"srand({seed});")]


def ensemble_path(tag):
    return os.path.join(CACHE, f"{tag}_ens.npz")


def ensemble(tag, force=False, verbose=True):
    """Compute (or load) the multi-seed spectra for one run."""
    path = ensemble_path(tag)
    if os.path.exists(path) and not force:
        if verbose:
            print(f"[cache] {tag} ensemble")
        return np.load(path, allow_pickle=True)

    params = configs.RUNS[tag]
    base_patches = configs.patches_for(tag)
    want_micro = configs.needs_micro(tag)
    want_exact = configs.needs_exact(tag)

    seeds = configs.seeds_for(tag)
    micro_bridge = configs.micro_bridge_for(tag)
    print(f"[ensemble] {tag}: {configs.describe(tag)}"
          f"  ({len(seeds)} seeds)")
    os.makedirs(CACHE, exist_ok=True)

    psd_meso, psd_micro = [], []
    rate_meso, rate_micro, mass_meso = [], [], []
    freq_meso = freq_micro = None

    for seed in seeds:
        print(f"\n  --- seed {seed} ---")
        workdir = run_solver(f"ens_{tag}_{seed}", params, verbose=verbose,
                             patches=base_patches + seed_patch(seed))
        try:
            act = np.memmap(os.path.join(workdir, "data", "activity.bin"),
                            dtype=np.float32, mode="r").reshape(-1, 2)
            n = act.shape[0]
            dt_ms = params["T_MAX"] / n
            activity = np.asarray(act[:, 0], dtype=np.float64) * 1000.0
            f, p = spectrum(activity, dt_ms / 1000.0,
                            skip_ms=configs.SPECTRUM_SKIP_MS)
            freq_meso = f if freq_meso is None else freq_meso
            psd_meso.append(p)
            rate_meso.append(float(activity[n // 3:].mean()))
            mass_meso.append(float(np.asarray(
                act[n // 3::max(1, n // 500_000), 1], dtype=np.float64).mean()))
            del activity
        finally:
            shutil.rmtree(workdir, ignore_errors=True)

        if want_micro:
            micro = run_micro(params, params["T_MAX"], seed=seed,
                              verbose=verbose, bridge=micro_bridge)
            f, p = spectrum(micro.astype(np.float64),
                            params["DT_NET"] / 1000.0,
                            skip_ms=configs.SPECTRUM_SKIP_MS)
            freq_micro = f if freq_micro is None else freq_micro
            psd_micro.append(p)
            rate_micro.append(float(micro.mean()))
            del micro

    out = {
        "tag": tag,
        "seeds": np.array(seeds),
        "dt_ms": params["T_MAX"] / n,
        "freq_meso": freq_meso,
        "psd_meso_all": np.vstack(psd_meso),
        "rate_meso": np.array(rate_meso),
        "mass_meso": np.array(mass_meso),
        "patched": bool(base_patches),
    }
    for key, v in params.items():
        out[f"param_{key}"] = v

    if want_micro:
        out["freq_micro"] = freq_micro
        out["psd_micro_all"] = np.vstack(psd_micro)
        out["rate_micro"] = np.array(rate_micro)

    # Reference quantities
    mu_dim = (params["MU"] - params["V_RESET"]) / \
        (params["V_TH"] - params["V_RESET"])
    sigma_dim = np.sqrt(params["D"]) / (params["V_TH"] - params["V_RESET"])
    rate_siegert = rate_whitenoise_benji(mu_dim, sigma_dim) * \
        (1000.0 / params["TAU"])
    cv, _ = derived(params)
    out["rate_siegert_hz"] = float(rate_siegert)
    out["cv"] = float(cv)

    if want_exact:
        # Same as above: no cap, the theory is stable and cheap.
        mask = freq_meso > 0.5
        f_th = freq_meso[mask]
        out["freq_exact"] = f_th
        out["psd_exact"] = exact_spectrum(f_th, params, rate_siegert)
        out["psd_poisson_level"] = rate_siegert / params["N_NEURONS"]
        out["psd_lowfreq_level"] = rate_siegert * cv ** 2 / params["N_NEURONS"]

    np.savez_compressed(path, **out)
    print(f"\n  cached -> {path} ({os.path.getsize(path) / 1e6:.1f} MB)")
    return np.load(path, allow_pickle=True)


def load_ensemble(tag):
    path = ensemble_path(tag)
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"no ensemble for '{tag}'. Run: python publication/make.py "
            f"ensemble --only {tag}")
    return np.load(path, allow_pickle=True)


def mean_band(psd_all, n_sd=1.0):
    """Mean spectrum across seeds and a +/- n_sd band, clipped positive."""
    mean = psd_all.mean(axis=0)
    sd = psd_all.std(axis=0, ddof=1)
    lo = np.clip(mean - n_sd * sd, 1e-30, None)
    return mean, lo, mean + n_sd * sd
