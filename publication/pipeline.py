# ==========================================================================
# Parameter header
# ==========================================================================
def derived(params):
    """CV and stationary rate, exactly as config.py computes them."""
    cv = cv_benji(params["MU"], params["D"])
    r0 = rate_whitenoise_benji(params["MU"], np.sqrt(params["D"]))
    return cv, r0


def write_header(path, params):
    cv, r0 = derived(params)
    full = dict(params)
    full["CV"] = cv
    full["R0"] = r0

    lines = ["#ifndef PARAMS_H", "#define PARAMS_H", "",
             "// Generated by publication/pipeline.py", ""]
    for key, val in full.items():
        if isinstance(val, int) and not isinstance(val, bool):
            lines.append(f"#define PARAM_{key} {val}")
        else:
            lines.append(f"#define PARAM_{key} {float(val):.8f}")
    lines += ["", "#endif", ""]

    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    return cv, r0


